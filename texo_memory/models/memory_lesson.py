from difflib import SequenceMatcher

from odoo import Command, api, fields, models
from odoo.exceptions import AccessError, UserError

from odoo.addons.texo import okf
from odoo.addons.texo.models.secrets import check_no_credential

from . import fulltext
from .leak_filter import forbidden_names, leak_reason

DUPLICATE_SIMILARITY = 0.6
PACK_LESSONS = 5
STATES = [('draft', "Draft"), ('active', "Active"), ('superseded', "Superseded"), ('archived', "Archived")]
MAX_READ = 6000
# The kind of a lesson as the type of its OKF concept.
OKF_TYPES = {'finding': 'Finding', 'lesson': 'Lesson', 'procedure': 'Playbook'}
# The tsvector is generated by PostgreSQL: the title weighs most, then the keywords (the
# synonyms and other names the writer gave), then the text; Italian and English stems side
# by side, so a query in either language matches, plus the plain words for codes and
# identifiers.
SEARCH_TSV = (
    "setweight(to_tsvector('simple', coalesce(name, '')), 'A') || "
    "setweight(to_tsvector('simple', coalesce(keywords, '')), 'B') || "
    "setweight(to_tsvector('italian', coalesce(keywords, '')), 'B') || "
    "setweight(to_tsvector('english', coalesce(keywords, '')), 'B') || "
    "setweight(to_tsvector('simple', coalesce(finding, '') || ' ' || coalesce(solution, '')), 'C') || "
    "setweight(to_tsvector('italian', coalesce(finding, '') || ' ' || coalesce(solution, '')), 'C') || "
    "setweight(to_tsvector('english', coalesce(finding, '') || ' ' || coalesce(solution, '')), 'C')"
)


class MemoryLesson(models.Model):
    """Knowledge that belongs to no customer: a finding written by an agent from the
    work on a project, a lesson curated by a lead, or a procedure.

    The model has no link to a customer, project, task or note: nothing in it can
    point back to the work it was learned on, so it survives a customer's opt-out
    and every hub member reads it, whatever projects they can see. It may belong to
    one of our companies (company_id, the current one by default): then only who
    works in that company reads it; without a company it is shared by all.
    """
    _name = 'memory.lesson'
    _description = "Memory Lesson"
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'write_date desc, id desc'

    name = fields.Char(string="Title", required=True, tracking=True)
    company_id = fields.Many2one('res.company', string="Company", index=True, default=lambda self: self.env.company,
                                 help="The company the lesson belongs to; empty, it is shared by every company.")
    kind = fields.Selection(
        [('finding', "Finding"), ('lesson', "Lesson"), ('procedure', "Procedure")],
        required=True, default='lesson', tracking=True,
        help="A finding is written by an agent from the work on a project; a lesson is curated by a lead.")
    # The native tags of the projects: a lesson reaches the pack of a task whose task or
    # project shares one of them, so the organisation indexes the two with the same words.
    tag_ids = fields.Many2many('project.tags', 'memory_lesson_project_tags_rel', 'lesson_id', 'tag_id', string="Tags",
                               help="What the lesson is about (a module, a version, an area): the context pack of a "
                                    "task gives the lessons that share a tag with the task or its project.")
    lesson_activity_ids = fields.Many2many(
        'memory.note.activity', 'memory_lesson_activity_rel', 'lesson_id', 'activity_id', string="Applies to",
        help="The work the lesson helps; none means every activity.")
    finding = fields.Text(required=True, help="The technical problem: version, models, fields, symptom.")
    solution = fields.Text(required=True, help="The reusable fix or pattern.")
    applies_to = fields.Char(help="Where it holds: Odoo version, modules, configuration.", index=True)
    keywords = fields.Char(help="Synonyms, translations and other names of what the lesson is about, comma "
                                "separated: the search finds it by these words too.")
    verified = fields.Char(help="How and when it was checked.")
    expires = fields.Date(help="After this day the lesson no longer holds on its own.")
    state = fields.Selection(STATES, required=True, default='draft', tracking=True, index=True)
    supersedes_id = fields.Many2one('memory.lesson', string="Supersedes", ondelete='set null')
    superseded_by_id = fields.Many2one('memory.lesson', string="Superseded By", ondelete='set null')
    origin = fields.Selection([('agent', "Agent"), ('person', "Person")], required=True, default='person')
    generated_by = fields.Char(
        string="Written By (Agent)",
        help="The agent that wrote the finding, as <producer>/<version>; empty, the tool of the hub it called.")
    merged_count = fields.Integer(default=1, help="How many findings this one gathers.")
    content_hash = fields.Char(compute='_compute_content_hash', store=True, index=True,
                               help="A fingerprint of finding and solution: the same text written again gives the "
                                    "existing lesson, nothing is written twice.")

    @api.depends('finding', 'solution')
    def _compute_content_hash(self):
        for lesson in self:
            lesson.content_hash = self.env['memory.note']._text_hash(f"{lesson.finding}\n{lesson.solution}")

    def init(self):
        self.env.cr.execute(
            "ALTER TABLE memory_lesson ADD COLUMN IF NOT EXISTS search_tsv tsvector "
            f"GENERATED ALWAYS AS ({SEARCH_TSV}) STORED")
        self.env.cr.execute(
            "CREATE INDEX IF NOT EXISTS memory_lesson_search_tsv_idx ON memory_lesson USING gin (search_tsv)")

    # -- guards ---------------------------------------------------------------
    def _check_lead(self):
        if not self.env.su and self.env.user._texo_role() not in ('lead', 'admin'):
            raise AccessError(self.env._("Only a Texo lead can change the state of a lesson."))

    def _check_clean(self, vals):
        """Refuse a shared text that names a customer, a person or a record, or holds a credential."""
        names = None
        check_no_credential(self.env, *(vals.get(key) for key in ('name', 'finding', 'solution', 'keywords')))
        for key in ('name', 'finding', 'solution', 'keywords'):
            if vals.get(key):
                if names is None:
                    names = forbidden_names(self.env)
                reason = leak_reason(self.env, vals[key], names=names, check_length=key not in ('name', 'keywords'))
                if reason:
                    raise UserError(self.env._("The lesson cannot be shared: %s.", reason))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            self._check_clean(vals)
        return super().create(vals_list)

    def write(self, vals):
        if 'state' in vals:
            self._check_lead()
        self._check_clean(vals)
        return super().write(vals)

    # -- state ----------------------------------------------------------------
    def action_activate(self):
        for lesson in self:
            lesson._agent_set_state('active')

    def action_archive_lesson(self):
        for lesson in self:
            lesson._agent_set_state('archived')

    def _agent_set_state(self, state, superseded_by_id=None):
        self.ensure_one()
        self._check_lead()
        vals = {'state': state}
        if state == 'superseded':
            later = self.browse(int(superseded_by_id or 0)).exists()
            if not later:
                raise UserError(self.env._("A superseded lesson needs the lesson that replaces it."))
            vals['superseded_by_id'] = later.id
            later.write({'supersedes_id': self.id})
        self.write(vals)
        return self._agent_summary()

    # -- reading --------------------------------------------------------------
    def _agent_summary(self):
        self.ensure_one()
        return {
            'id': self.id, 'concept': okf.concept_id(self), 'title': self.name, 'kind': self.kind, 'tags': self.tag_ids.mapped('name'),
            'activities': self.lesson_activity_ids.mapped('code'), 'state': self.state,
            'applies_to': self.applies_to or None, 'verified': self.verified or None,
            'expires': fields.Date.to_string(self.expires) if self.expires else None,
        }

    def _agent_read(self, max_chars=MAX_READ):
        self.ensure_one()
        result = self._agent_summary()
        result.update({'finding': self.finding[:max_chars], 'solution': self.solution[:max_chars],
                       'keywords': self.keywords or None})
        return result

    def _okf_concept(self):
        """The lesson as an OKF concept: its kind as the type, its project tags as tags, the
        finding and the solution as the body. No anchor and no author: a lesson points back
        to no work."""
        self.ensure_one()
        meta = {
            'type': OKF_TYPES[self.kind], 'title': self.name, 'description': okf.description(self.finding),
            'tags': self.tag_ids.mapped('name'), 'status': okf.status(self.state),
            # anonymous: the lesson names no one and its time no session it could be matched with
            'generated': okf.generated(self.origin, self.create_uid, self.generated_by, self.write_date,
                                       anonymous=True),
            'stale_after': okf.stale_after(okf.day_after(self.expires)),
            'activities': self.lesson_activity_ids.mapped('code'), 'applies_to': self.applies_to or None,
            'checked': self.verified or None, 'keywords': self.keywords or None,
            'supersedes': okf.link(self.supersedes_id) if self.supersedes_id else None,
            'superseded_by': okf.link(self.superseded_by_id) if self.superseded_by_id else None,
        }
        return okf.concept(meta, f"# Finding\n\n{self.finding}\n\n# Solution\n\n{self.solution}")

    def _live_domain(self, include_draft=False, show_expired=False):
        today = fields.Date.context_today(self)
        domain = [('state', 'in', ('draft', 'active') if include_draft else ('active',))]
        if not show_expired:
            domain += ['|', ('expires', '=', False), ('expires', '>=', today)]
        return domain

    @api.model
    def _agent_search(self, query, related_terms=None, applies_to=None, limit=5, include_draft=False,
                      show_expired=False):
        """Lessons ranked by PostgreSQL full-text search over title, keywords and text: first
        those that hold every word (a long word also as a prefix), then, only to fill the
        limit, those that hold some (fulltext.rank)."""
        limit = max(1, min(int(limit or 5), 20))
        lessons, ranked = fulltext.search(self, 'memory_lesson', 'search_tsv', fulltext.words(query, related_terms),
                                          limit, self._search_domain(applies_to, include_draft, show_expired))
        return lessons._search_entries(ranked)

    def _search_domain(self, applies_to=None, include_draft=False, show_expired=False):
        return (self._live_domain(include_draft, show_expired)
                + ([('applies_to', 'ilike', applies_to)] if applies_to else []))

    def _search_entries(self, ranked):
        """The search results of these lessons, in this order: the summary, the score and the
        words (fulltext.fields of ranked), the first words of the finding, flagged as lessons."""
        today = fields.Date.context_today(self)
        return [dict(lesson._agent_summary(), **fulltext.fields(ranked, lesson.id), snippet=(lesson.finding or '')[:160],
                     lesson=True, updated=fields.Date.to_string(lesson.write_date),
                     **({'stale': 'expired'} if lesson.expires and lesson.expires < today else {}))
                for lesson in self]

    @api.model
    def _agent_pack(self, tags, activities=None, limit=PACK_LESSONS):
        """The lessons of a context pack: the active ones that share a tag with the task or
        its project, those that share more first; with the activity of the session, those of
        that activity and of every activity. No tag, no lesson: the pack does not guess from
        the words of a title."""
        if not tags:
            return []
        domain = [('tag_ids', 'in', tags.ids)] + self._live_domain()
        if activities:
            domain += ['|', ('lesson_activity_ids', '=', False), ('lesson_activity_ids', 'in', activities.ids)]
        lessons = self.search(domain).sorted(key=lambda l: (-len(l.tag_ids & tags), -l.id))[:limit]
        # An outline: the agent reads the lessons it needs (memory/read), the pack stays small.
        return [{'id': lesson.id, 'concept': okf.concept_id(lesson), 'title': lesson.name, 'tags': lesson.tag_ids.mapped('name'),
                 'applies_to': lesson.applies_to or None} for lesson in lessons]

    @api.model
    def _tags_from_names(self, names):
        """The project tags of these names, a list or a comma-separated text; a missing one is
        created (the tags are the vocabulary of the organisation, the consolidation merges them)."""
        if isinstance(names, str):
            names = names.split(',')
        Tag = self.env['project.tags']
        tags = Tag.browse()
        for name in {n.strip() for n in names or [] if n and n.strip()}:
            # sudo: a project user reads the tags but may not create them; the name passed
            # the leak filter with the lesson
            tag = Tag.sudo().search([('name', '=ilike', name)], limit=1) or Tag.sudo().create({'name': name})
            tags |= tag
        return tags.sudo(False)

    # -- finding --------------------------------------------------------------
    @api.model
    def _agent_lesson(self, finding, solution, tags=None, title=None, applies_to=None, verified=None,
                      state='draft', source_ref=None, activities=None, keywords=None, generated_by=None):
        """Write a finding as the user: something learned on a project, without
        the project. A member's is a draft for the leads; a lead's may be active at once.
        source_ref (the task it comes from) only feeds the leak filter: nothing in the
        lesson points back to the work. Idempotent: the same finding and solution already
        live give that lesson, with existing true, and nothing is written."""
        role = self.env.user._texo_check_role()
        if state not in ('draft', 'active'):
            raise UserError(self.env._("A new lesson is a draft or active."))
        if state == 'active' and role == 'member':
            raise AccessError(self.env._("A member writes drafts; a lead reviews them."))
        if not (finding or '').strip() or not (solution or '').strip():
            raise UserError(self.env._("A finding needs finding and solution."))
        shared = {'finding': finding, 'solution': solution, 'tags': tags, 'title': title,
                  'applies_to': applies_to, 'verified': verified, 'activities': activities,
                  'keywords': ", ".join(keywords) if isinstance(keywords, (list, tuple)) else keywords,
                  'generated_by': okf.actor(generated_by)}
        lesson, created = self._publish_finding(shared, state, source_ref)
        return lesson._agent_summary() if created else dict(lesson._agent_summary(), existing=True)

    @api.model
    def _publish_finding(self, shared, state, source_ref=None):
        """Create a finding that belongs to no customer: (the lesson, whether it was created now).
        Raises when the text would leak: nothing is stored in that case. The same finding and
        solution already live, once the filter passed, are given back and nothing is written."""
        names = forbidden_names(self.env)
        for key in ('finding', 'solution', 'keywords'):
            if key == 'keywords' and not shared.get(key):
                continue
            reason = leak_reason(self.env, shared.get(key), source_ref, names, check_length=key != 'keywords')
            if reason:
                raise UserError(self.env._("The shared finding cannot be stored: %s. Rewrite it and try again.", reason))
        tag_names = shared.get('tags') or []
        if isinstance(tag_names, str):
            tag_names = tag_names.split(',')
        for name in tag_names:
            reason = leak_reason(self.env, name, source_ref, names, check_length=False)
            if reason:
                raise UserError(self.env._("The tag %(tag)s cannot be stored: %(reason)s.", tag=name, reason=reason))
        # the filter passed: the same finding and solution already live are given back, nothing is written
        existing = self.search([('state', 'in', ('draft', 'active')),
                                ('content_hash', '=', self.env['memory.note']._text_hash(
                                    f"{shared['finding'].strip()}\n{shared['solution'].strip()}"))],
                               order='id', limit=1)
        if existing:
            return existing, False
        tags = self._tags_from_names(tag_names)
        activities = self.env['memory.note.activity']._from_codes(shared.get('activities'))
        title = (shared.get('title') or shared['finding']).strip()[:120]
        # sudo: a member may not create lessons on their own; the finding passed the
        # filter above and is the only way a member's knowledge reaches the shared store.
        lesson = self.sudo().with_context(mail_create_nolog=True, mail_notrack=True).create({
            'name': title, 'kind': 'finding', 'origin': 'agent', 'state': state,
            'tag_ids': [Command.set(tags.ids)], 'lesson_activity_ids': [Command.set(activities.ids)],
            'finding': shared['finding'].strip(), 'solution': shared['solution'].strip(),
            'applies_to': shared.get('applies_to'), 'verified': shared.get('verified'),
            'keywords': shared.get('keywords') or False, 'generated_by': shared.get('generated_by') or False,
        })
        # The ORM never writes the magic dates, and an exact timestamp could be matched
        # with the chatter of the task it was learned on: truncate them to the day in SQL.
        self.env.cr.execute(
            "UPDATE memory_lesson SET create_date = date_trunc('day', create_date), "
            "write_date = date_trunc('day', write_date) WHERE id = %s", [lesson.id])
        lesson.invalidate_recordset(['create_date', 'write_date'])
        return lesson, True

    def _leads(self):
        return self.env.ref('texo.group_texo_lead').sudo().all_user_ids.filtered('active')

    @api.model
    def _duplicate_pairs(self, similarity=DUPLICATE_SIMILARITY, lessons=None):
        """[(first, second, ratio)] of live lessons about the same thing (a tag in common, or
        both without tags) that say almost the same, by difflib ratio; deterministic, older
        lesson first."""
        lessons = lessons if lessons is not None else self.search([('state', 'in', ('draft', 'active'))], order='id')
        pairs = []
        for i, first in enumerate(lessons):
            for second in lessons[i + 1:]:
                if (first.tag_ids or second.tag_ids) and not first.tag_ids & second.tag_ids:
                    continue
                ratio = SequenceMatcher(None, f"{first.finding} {first.solution}".lower(),
                                        f"{second.finding} {second.solution}".lower()).ratio()
                if ratio >= similarity:
                    pairs.append((first, second, int(ratio * 100)))
        return pairs

    @api.model
    def _cron_housekeeping(self, similarity=DUPLICATE_SIMILARITY):
        """Weekly: archive a lesson that names a customer created after it was written
        and tell the leads; propose the merge of near-duplicates (a tag in common) with one
        activity per pair, never twice; ask to re-check the stale rules.
        The person decides, nothing is merged on its own."""
        names = forbidden_names(self.env)
        live = self.search([('state', 'in', ('draft', 'active'))], order='id')
        leaked = live.filtered(lambda l: leak_reason(self.env, l.finding, names=names)
                               or leak_reason(self.env, l.solution, names=names))
        for lesson in leaked:
            lesson.write({'state': 'archived'})
            lesson.message_post(body=self.env._("Archived by the housekeeping: the text names a customer."),
                                message_type='comment', subtype_xmlid='mail.mt_note')
        duplicates = 0
        summary = self.env._("Possible duplicate lesson")
        for first, second, ratio in self._duplicate_pairs(similarity, live - leaked):
            duplicates += 1
            note = self.env._("Lesson %(first)s says almost the same (%(ratio)s%%): merge or supersede one.",
                              first=first.id, ratio=ratio)
            marker = str(first.id)
            if second.activity_ids.filtered(lambda a, marker=marker: a.summary == summary and marker in (a.note or '')):
                continue
            for user in self._leads():
                second.activity_schedule('mail.mail_activity_data_todo', user_id=user.id, summary=summary, note=note)
        stale = self.env['memory.note']._cron_housekeeping()
        return {'archived': len(leaked), 'duplicates': duplicates, 'stale': stale}
